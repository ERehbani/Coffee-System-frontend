import { PurchaseResponseDto } from '../types/checkout.dto';
import {
  buildPurchaseResponse,
  CHECKOUT_CAFE_FIXTURE,
  CHECKOUT_ITEMS_FIXTURE,
} from './checkout.fixture';
import { toCheckoutSummary, toConfirmedOrder, toCreatePurchaseRequestDto } from './checkout.mapper';

describe('checkout mapper', () => {
  describe('toCheckoutSummary', () => {
    it('lists each product with its quantity, unit price and subtotal', () => {
      const summary = toCheckoutSummary(CHECKOUT_CAFE_FIXTURE, CHECKOUT_ITEMS_FIXTURE);

      expect(summary?.cafeId).toBe('cafe-central-001');
      expect(summary?.cafeName).toBe('Cafe Central');
      expect(summary?.lines).toEqual([
        {
          productId: 'prod-central-001',
          productName: 'Espresso Doble',
          quantity: 2,
          unitPrice: 2800,
          subtotal: 5600,
        },
        {
          productId: 'prod-central-002',
          productName: 'Flat White',
          quantity: 1,
          unitPrice: 3600,
          subtotal: 3600,
        },
      ]);
    });

    it('adds the subtotals into the total', () => {
      expect(toCheckoutSummary(CHECKOUT_CAFE_FIXTURE, CHECKOUT_ITEMS_FIXTURE)?.total).toBe(9200);
    });

    it('returns null when the cart has no products or no cafe', () => {
      expect(toCheckoutSummary(CHECKOUT_CAFE_FIXTURE, [])).toBeNull();
      expect(toCheckoutSummary(null, CHECKOUT_ITEMS_FIXTURE)).toBeNull();
    });
  });

  describe('toCreatePurchaseRequestDto', () => {
    it('sends only the cart id when there is no validation code', () => {
      expect(toCreatePurchaseRequestDto({ cartId: 'cart-1' })).toEqual({ cartId: 'cart-1' });
    });

    it('drops a blank validation code', () => {
      expect(toCreatePurchaseRequestDto({ cartId: 'cart-1', validationCode: '   ' })).toEqual({
        cartId: 'cart-1',
      });
    });

    it('sends the trimmed validation code when there is one', () => {
      expect(
        toCreatePurchaseRequestDto({ cartId: 'cart-1', validationCode: ' VLD-0001-ABCD ' }),
      ).toEqual({ cartId: 'cart-1', validationCode: 'VLD-0001-ABCD' });
    });
  });

  describe('toConfirmedOrder', () => {
    const response: PurchaseResponseDto = buildPurchaseResponse(
      'purchase-123',
      CHECKOUT_CAFE_FIXTURE,
      CHECKOUT_ITEMS_FIXTURE,
      new Date('2026-11-13T10:30:00Z'),
    );

    it('keeps the order number, the total and the cafe', () => {
      const order = toConfirmedOrder(response);

      expect(order.orderNumber).toBe('purchase-123');
      expect(order.total).toBe(9200);
      expect(order.cafeId).toBe('cafe-central-001');
      expect(order.cafeName).toBe('Cafe Central');
      expect(order.redemptionId).toBeNull();
      expect(order.date).toEqual(new Date('2026-11-13T10:30:00Z'));
    });

    it('adds the points generated by every detail', () => {
      expect(toConfirmedOrder(response).generatedPoints).toBe(2 * 50 + 70);
    });

    it('maps the details into order lines', () => {
      expect(toConfirmedOrder(response).lines[0]).toEqual({
        productId: 'prod-central-001',
        productName: 'Espresso Doble',
        quantity: 2,
        unitPrice: 2800,
        subtotal: 5600,
        generatedPoints: 100,
      });
    });

    it.each([
      ['CONFIRMED', 'confirmed'],
      ['CANCELLED', 'cancelled'],
      ['REFUNDED', 'refunded'],
    ] as const)('maps the status %s to %s', (status, expected) => {
      expect(toConfirmedOrder({ ...response, status }).status).toBe(expected);
    });
  });
});
